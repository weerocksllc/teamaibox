export function applyShellCopy() {
  const path = new URL('../apps/web/src/i18n.ts', import.meta.url);
  let source = readFileSync(path, 'utf8');
  for (const [key, values] of Object.entries(shellCopy)) {
    let index = 0;
    const pattern = new RegExp('("' + key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '"\\s*:\\s*)"(?:[^"\\\\]|\\\\.)*"', 'g');
    source = source.replace(pattern, (_, prefix) => prefix + JSON.stringify(values[index++]));
    if (index !== 2) throw Error(`${key}: expected two locale entries, got ${index}`);
  }
  writeFileSync(path, source);
  return Object.keys(shellCopy).length;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) console.log({ bilingualKeys: applyShellCopy() });
