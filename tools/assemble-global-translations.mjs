import {readFile,writeFile} from 'node:fs/promises';
import {localeDefinitions} from '../packages/ui-system/src/locale-registry.mjs';
import {applyGlossary} from '../packages/ui-system/src/locale-glossary.mjs';
const translations={};
for(const {code} of localeDefinitions){if(['en','zh-CN'].includes(code))continue;
 try{translations[code]=applyGlossary(code,JSON.parse(await readFile(new URL(`../packages/ui-system/src/locales/${code}.json`,import.meta.url),'utf8')));}
 catch{translations[code]={};}
}
await writeFile(new URL('../packages/ui-system/src/global-translations.mjs',import.meta.url),`// Generated by tools/assemble-global-translations.mjs. Edit locale sources, not this file.\nexport const translations = ${JSON.stringify(translations)};\n`);
console.log(Object.fromEntries(Object.entries(translations).map(([locale,values])=>[locale,Object.keys(values).length])));
