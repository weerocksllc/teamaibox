export const localeDirections = Object.freeze(Object.fromEntries(localeDefinitions.map(({code,direction})=>[code,direction]))) as Readonly<Record<Locale, "ltr" | "rtl">>;

function createNamespacedCatalog(flatCatalog: Readonly<Record<string, string>>) {
  const namespaces: Record<string, Record<string, string>> = {};
  for (const [key, value] of Object.entries(flatCatalog)) {
    const separator = key.indexOf(".");
    const namespace = separator === -1 ? "common" : key.slice(0, separator);
    const messageKey = separator === -1 ? key : key.slice(separator + 1);
    namespaces[namespace] ??= {};
    namespaces[namespace][messageKey] = value;
  }
  return Object.freeze(Object.fromEntries(
    Object.entries(namespaces).map(([namespace, messages]) => [namespace, Object.freeze(messages)]),
  ));
}

export const namespacedCatalogs = Object.freeze(Object.fromEntries(
  supportedLocales.map((locale) => [locale, createNamespacedCatalog(catalogs[locale])]),
)) as Readonly<Record<Locale, Readonly<Record<string, Readonly<Record<string, string>>>>>>;

export type I18nDiagnostic = Readonly<{
  kind: "fallback" | "missing";
  locale: string;
  fallbackLocale: Locale;
  key: string;
}>;

type RuntimeCatalogs = Readonly<Record<string, Readonly<Record<string, string>>>>;
type FormatValues = Readonly<Record<string, string | number | boolean | bigint | Date>>;

export function normalizeLocale(candidate: unknown): Locale {
  return normalizeProductLocale(candidate, fallbackLocale);
}

function interpolate(template: string, values: FormatValues = {}) {
  return template.replace(/\{([a-zA-Z][a-zA-Z0-9_]*)\}/g, (placeholder, key) =>
    Object.hasOwn(values, key) ? String(values[key]) : placeholder,
  );
}

export function createI18nRuntime({
  locale,
  onDiagnostic = () => {},
  catalogSet = catalogs,
  fallback = fallbackLocale,
}: {
  locale: unknown;
  onDiagnostic?: (diagnostic: I18nDiagnostic) => void;
  catalogSet?: RuntimeCatalogs;
  fallback?: Locale;
}) {
  const activeLocale = normalizeLocale(locale);
  const activeCatalog = catalogSet[activeLocale] ?? {};
  const fallbackCatalog = catalogSet[fallback] ?? {};
  const reported = new Set<string>();

  function diagnostic(kind: I18nDiagnostic["kind"], key: string) {
    const signature = `${kind}:${activeLocale}:${key}`;
    if (reported.has(signature)) return;
    reported.add(signature);
    onDiagnostic(Object.freeze({ kind, locale: activeLocale, fallbackLocale: fallback, key }));
  }

  function translate(key: string, values?: FormatValues) {
    if (Object.hasOwn(activeCatalog, key)) return interpolate(activeCatalog[key], values);
    if (Object.hasOwn(fallbackCatalog, key)) {
      diagnostic("fallback", key);
      return interpolate(fallbackCatalog[key], values);
    }
    diagnostic("missing", key);
    return key;
  }

  return Object.freeze({
    locale: activeLocale,
    direction: localeDirections[activeLocale],
    translate,
    formatDateTime(value: string | number | Date, options: Intl.DateTimeFormatOptions = {}) {
      return new Intl.DateTimeFormat(activeLocale, options).format(new Date(value));
    },
    formatNumber(value: number | bigint, options: Intl.NumberFormatOptions = {}) {
      return new Intl.NumberFormat(activeLocale, options).format(value);
    },
    formatUnit(value: number | bigint, unit: string, options: Intl.NumberFormatOptions = {}) {
      return new Intl.NumberFormat(activeLocale, { style: "unit", unit, ...options }).format(value);
    },
    formatList(values: Iterable<string>, options: Intl.ListFormatOptions = {}) {
      return new Intl.ListFormat(activeLocale, options).format([...values]);
    },
    formatRelativeTime(value: number, unit: Intl.RelativeTimeFormatUnit, options: Intl.RelativeTimeFormatOptions = {}) {
      return new Intl.RelativeTimeFormat(activeLocale, options).format(value, unit);
    },
    pluralCategory(value: number, options: Intl.PluralRulesOptions = {}) {
      return new Intl.PluralRules(activeLocale, options).select(value);
    },
    selectPlural(value: number, variants: Readonly<Record<string, string>>) {
      const exact = variants[`=${value}`];
      const selected = exact ?? variants[new Intl.PluralRules(activeLocale).select(value)] ?? variants.other;
      if (typeof selected !== "string") throw new TypeError("plural variants require an other value");
      return interpolate(selected, { count: value });
    },
  });
}
